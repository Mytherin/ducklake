def escape_cell(text):
    return text.replace('|', '\\|').replace('\n', ' ')


def field_table(spec, obj):
    fields = spec.fields_of(obj)
    if not fields:
        return ['No fields.']
    lines = ['| Field | Type | Description |', '|-------|------|-------------|']
    for field in fields:
        type_doc = spec.doc_type(field.type)
        notes = []
        if field.nullable:
            notes.append('optional')
        if field.default is not None:
            notes.append(f'default `{json.dumps(field.default)}`')
        if notes:
            type_doc += f' ({", ".join(notes)})'
        description = field.description
        if field.key_field:
            key = f'`{field.key_field}`'
            if field.value_field:
                description = f'Entries of `{field.key_field}` and `{field.value_field}`. ' + description
            else:
                description = f'Each entry has an additional field {key}. ' + description
        lines.append(f'| `{field.name}` | {escape_cell(type_doc)} | {escape_cell(description.strip())} |')
    return lines


def generate_docs(spec):
    lines = [DOCS_BEGIN, '']
    for section in spec.sections:
        lines.append(f'## {section.title}')
        lines.append('')
        if section.description:
            lines.append(section.description)
            lines.append('')
        for endpoint in section.endpoints:
            lines.append(f'### `{endpoint.name}`')
            lines.append('')
            if endpoint.summary:
                lines.append(endpoint.summary)
                lines.append('')
            if endpoint.description:
                lines.append(endpoint.description)
                lines.append('')
            if endpoint.request in endpoint.own_bodies():
                if spec.fields_of(endpoint.request):
                    lines.append('Request:')
                    lines.append('')
                    lines.extend(field_table(spec, endpoint.request))
                else:
                    lines.append('Request: an empty object.')
            else:
                lines.append(f'Request: [`{endpoint.request.name}`](#{endpoint.request.name.lower()}).')
            lines.append('')
            if endpoint.kind == 'commit':
                lines.append(f'Response: as for [`{COMMIT_ENDPOINT}`](#{COMMIT_ENDPOINT}).')
            elif not endpoint.response:
                lines.append('Response: an empty object.')
            elif endpoint.response in endpoint.own_bodies():
                lines.append('Response:')
                lines.append('')
                lines.extend(field_table(spec, endpoint.response))
            else:
                lines.append(f'Response: [`{endpoint.response.name}`](#{endpoint.response.name.lower()}).')
            lines.append('')
        for entry in section.types:
            lines.append(f'### `{entry.name}`')
            lines.append('')
            if entry.description:
                lines.append(entry.description)
                lines.append('')
            if isinstance(entry, UnionType):
                lines.append('An object with exactly one member, the name of the variant:')
                lines.append('')
                lines.append('| Variant | Type |')
                lines.append('|---------|------|')
                for wire_name, struct_name in entry.variants:
                    lines.append(f'| `{wire_name}` | [`{struct_name}`](#{struct_name.lower()}) |')
            elif isinstance(entry, EnumType):
                lines.append('| Value | Description |')
                lines.append('|-------|-------------|')
                for value in entry.values:
                    lines.append(f'| `{value["name"]}` | {escape_cell(description_text(value))} |')
            else:
                if entry.extends and not entry.fields:
                    lines.append(f'Has the fields of [`{entry.extends}`](#{entry.extends.lower()}).')
                elif entry.extends:
                    lines.append(f'Has the fields of [`{entry.extends}`](#{entry.extends.lower()}), and:')
                    lines.append('')
                    fields = entry.fields
                    tmp = ObjectType({'name': entry.name, 'fields': []}, section)
                    tmp.fields = fields
                    lines.extend(field_table(spec, tmp))
                else:
                    lines.extend(field_table(spec, entry))
            lines.append('')
    lines.append(DOCS_END)
    return '\n'.join(lines)


def update_docs(spec, current):
    begin = current.find(DOCS_BEGIN)
    end = current.find(DOCS_END)
    if begin < 0 or end < 0:
        raise SpecError(f'{DOCS_PATH} has no generated reference section')
    return current[:begin] + generate_docs(spec) + current[end + len(DOCS_END) :]


def format_cpp(content, path):
    """Formats generated code like scripts/format.py of DuckDB does"""
    try:
        result = subprocess.run(
            ['clang-format', '--sort-includes=0', '-style=file', f'--assume-filename={path}'],
            input=content,
            capture_output=True,
            text=True,
            cwd=ROOT,
        )
    except FileNotFoundError:
        raise SpecError('clang-format is required to generate the code (pip install clang_format==11.0.1)')
    if result.returncode != 0:
        raise SpecError(f'clang-format failed: {result.stderr}')
    return result.stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='Fail if the generated files are out of date')
    args = parser.parse_args()
    try:
        spec = Spec(SmithyModel(load_smithy_ast(SPEC_DIR)).sections())
        with open(DOCS_PATH, 'r') as f:
            docs = f.read()
        outputs = {
            HEADER_PATH: format_cpp(generate_header(spec), HEADER_PATH),
            SOURCE_PATH: format_cpp(generate_source(spec), SOURCE_PATH),
            DOCS_PATH: update_docs(spec, docs),
        }
    except SpecError as ex:
        print(f'Error in the REST API specification: {ex}', file=sys.stderr)
        sys.exit(1)
    outdated = []
    for path, content in outputs.items():
        current = None
        if os.path.exists(path):
            with open(path, 'r') as f:
                current = f.read()
        if current == content:
            continue
        outdated.append(os.path.relpath(path, ROOT))
        if not args.check:
            with open(path, 'w') as f:
                f.write(content)
    if args.check:
        model_format = subprocess.run([find_smithy(), 'format', '--check', SPEC_DIR], capture_output=True, text=True)
        if model_format.returncode != 0:
            outdated.append(f'{os.path.relpath(SPEC_DIR, ROOT)} (run smithy format)')
    if args.check and outdated:
        print(f'Generated REST API files are out of date: {", ".join(outdated)}', file=sys.stderr)
        print('Run python3 scripts/generate_rest_api.py', file=sys.stderr)
        sys.exit(1)


if __name__ == '__main__':
    main()
