    lines.append('};')
    lines.append('')
    for obj in all_objects:
        lines.append(f'template <>')
        lines.append(f'{obj.cpp_name} DuckLakeRESTSerializer::Read(RESTJsonIn in);')
    lines.append('')
    lines.append('template <class T>')
    lines.append('struct RESTObjectCodec : public RESTCodec<RESTObjectCodec<T>> {')
