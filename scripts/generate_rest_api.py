def topological_order(spec, objects):
    """Orders the DTOs so that every structure is declared after the structures it holds"""
    by_name = {obj.name: obj for obj in objects}
    order = []
    visited = set()

    def dependencies(expr, result):
        if expr.kind == 'named' and expr.name in by_name:
            result.append(expr.name)
        for arg in expr.args:
            dependencies(arg, result)

    def visit(obj, stack):
        if obj.name in visited:
            return
        if obj.name in stack:
            raise SpecError(f'Types {stack} hold each other')
        deps = []
        if obj.extends and obj.extends in by_name:
            deps.append(obj.extends)
        for field in obj.fields:
            dependencies(field.type, deps)
        for dep in deps:
            visit(by_name[dep], stack + [obj.name])
        visited.add(obj.name)
        order.append(obj)

    for obj in objects:
        visit(obj, [])
    return order


def write_field(spec, field, lines):
    member = f'value.{field.member}'
    expr = field.type
    if expr.kind == 'map':
        key_codec = spec.codec(expr.args[0])
        value_codec = spec.codec(expr.args[1])
        lines.append(f'\t{{')
        lines.append(f'\t\tauto entries = writer.CreateArray();')
        lines.append(f'\t\tfor (auto &entry : {member}) {{')
        if field.value_field:
            lines.append(f'\t\t\tauto item = writer.CreateObject();')
            lines.append(
                f'\t\t\titem.Add({cpp_string(field.key_field)}, RESTWriteValue<{key_codec}>(writer, entry.first));'
            )
            lines.append(
                f'\t\t\titem.Add({cpp_string(field.value_field)}, '
                f'RESTWriteValue<{value_codec}>(writer, entry.second));'
            )
        else:
            lines.append(f'\t\t\tauto item = RESTWriteValue<{value_codec}>(writer, entry.second);')
            lines.append(
                f'\t\t\titem.Add({cpp_string(field.key_field)}, RESTWriteValue<{key_codec}>(writer, entry.first));'
            )
        lines.append(f'\t\t\tentries.Append(item);')
        lines.append(f'\t\t}}')
        lines.append(f'\t\tresult.Add({cpp_string(field.name)}, entries);')
        lines.append(f'\t}}')
        return
    write = f'RESTWriteValue<{spec.codec(expr)}>(writer, {member})'
    if expr.kind == 'primitive' and expr.name == 'rows':
        write = f'RESTRowsCodec::Write(writer, {member})'
    add = f'result.Add({cpp_string(field.name)}, {write});'
    if field.has_member:
        lines.append(f'\tif (value.{field.has_member}) {{')
        lines.append(f'\t\t{add}')
        lines.append(f'\t}}')
    elif field.null_member:
        lines.append(f'\tif (!value.{field.null_member}) {{')
        lines.append(f'\t\t{add}')
        lines.append(f'\t}}')
    elif field.nullable:
        lines.append(f'\tif (!RESTIsNull({member})) {{')
        lines.append(f'\t\t{add}')
        lines.append(f'\t}}')
    else:
        lines.append(f'\t{add}')


def row_types_code(spec, obj, field):
    """The code that computes the types of the rows of a rows field"""
    parts = field.row_types.split('.')
    fields = {f.name: f for f in spec.fields_of(obj)}
    source = fields[parts[0]]
    if len(parts) == 1:
        return f'result.{source.member}'
    if source.type.kind != 'list' or source.type.args[0].kind != 'named':
        raise SpecError(f'{obj.name}.{field.name}: row_types can only refer to fields of a list of objects')
    element = spec.types[source.type.args[0].name]
    element_fields = {f.name: f for f in spec.fields_of(element)}
    if parts[1] not in element_fields:
        raise SpecError(f'{obj.name}.{field.name}: {element.name} has no field "{parts[1]}"')
    return f'RESTRowTypes(result.{source.member}, &{element.cpp_name}::{element_fields[parts[1]].member})'


def read_field(spec, obj, field, lines):
    member = f'result.{field.member}'
    expr = field.type
    required = not field.nullable and field.default is None
    get = 'Get' if required else 'TryGet'
    if expr.kind == 'map':
        key_codec = spec.codec(expr.args[0])
        value_codec = spec.codec(expr.args[1])
        lines.append(f'\tfor (auto &item : in.{get}({cpp_string(field.name)}).Items()) {{')
        lines.append(f'\t\tusing map_t = decltype({member});')
        lines.append(
            f'\t\tauto key = {key_codec}::template Get<typename map_t::key_type>('
            f'item.Get({cpp_string(field.key_field)}));'
        )
        item = f'item.Get({cpp_string(field.value_field)})' if field.value_field else 'item'
        lines.append(f'\t\t{member}.emplace(key, {value_codec}::template Get<typename map_t::mapped_type>({item}));')
        lines.append(f'\t}}')
        return
    if expr.kind == 'primitive' and expr.name == 'rows':
        read = f'RESTRowsCodec::Read({{entry}}, {member}, {row_types_code(spec, obj, field)});'
    else:
        read = f'RESTReadValue<{spec.codec(expr)}>({{entry}}, {member});'
    if required:
        lines.append('\t' + read.format(entry=f'in.Get({cpp_string(field.name)})'))
        return
    lines.append(f'\t{{')
    lines.append(f'\t\tauto entry = in.TryGet({cpp_string(field.name)});')
    if field.has_member:
        lines.append(f'\t\tresult.{field.has_member} = !entry.IsNull();')
        lines.append(f'\t\tif (result.{field.has_member}) {{')
    elif field.null_member:
        lines.append(f'\t\tresult.{field.null_member} = entry.IsNull();')
        lines.append(f'\t\tif (!result.{field.null_member}) {{')
    else:
        lines.append(f'\t\tif (!entry.IsNull()) {{')
    lines.append('\t\t\t' + read.format(entry='entry'))
    if field.default is not None and spec.default_literal(field) is not None:
        lines.append(f'\t\t}} else {{')
        lines.append(f'\t\t\t{member} = {spec.default_literal(field)};')
    lines.append(f'\t\t}}')
    lines.append(f'\t}}')


def doc_comment(text, indent):
    if not text:
        return []
    first = text.split('\n')[0]
    return [f'{indent}//! {first}']


